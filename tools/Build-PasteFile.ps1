#Requires -Version 7.2
<#
.SYNOPSIS
    Builds dist/EverythingIsFine.ps1: the whole module as one block to copy and paste into a PowerShell 7 console.
.DESCRIPTION
    Engineers can't run unsigned .ps1 files on their work devices, so they paste this file instead.
    Everything is wrapped in one dot-sourced script block, so:
      - the console treats the paste as a single statement (it all loads, or none of it does);
      - the version / language-mode checks at the top can stop the load cleanly;
      - functions land in the console session, where $script: resolves to the global scope.
    Output is deterministic (no timestamps) so CI can check the committed file is up to date.
.EXAMPLE
    ./tools/Build-PasteFile.ps1
#>
[CmdletBinding()]
param(
    [string]$OutputPath
)

$ErrorActionPreference = 'Stop'
$repo = if ($PSScriptRoot) { Split-Path $PSScriptRoot -Parent } else { (Get-Location).Path }
$moduleDir = Join-Path $repo 'src' 'EverythingIsFine'
if (-not $OutputPath) { $OutputPath = Join-Path $repo 'dist' 'EverythingIsFine.ps1' }

$version = (Import-PowerShellDataFile (Join-Path $moduleDir 'EverythingIsFine.psd1')).ModuleVersion
$public = @(Get-ChildItem (Join-Path $moduleDir 'Public') -Filter '*.ps1' | Sort-Object Name)
$private = @(Get-ChildItem (Join-Path $moduleDir 'Private') -Filter '*.ps1' | Sort-Object Name)

$header = @"
# =====================================================================================
# EverythingIsFine v$version - PASTE BUILD
# Microsoft 365 BEC triage / containment / investigation toolkit.
#
# HOW TO USE: open PowerShell 7 (pwsh), select ALL of this file, copy, and paste it into
# the console. When it finishes you'll see a "loaded" message. Then run:
#     Connect-IR -Tenant <client-domain>
#
# GENERATED by tools/Build-PasteFile.ps1 from src/. Do not edit this file directly.
# =====================================================================================
. {
    if (`$PSVersionTable.PSVersion.Major -lt 7) {
        Write-Host 'EverythingIsFine needs PowerShell 7. This window is Windows PowerShell 5.1. Run "pwsh" and paste again.' -ForegroundColor Red
        return
    }
    if (`$ExecutionContext.SessionState.LanguageMode -ne 'FullLanguage') {
        Write-Host "EverythingIsFine needs FullLanguage mode; this session is '`$(`$ExecutionContext.SessionState.LanguageMode)' (AppLocker/WDAC). Not loaded." -ForegroundColor Red
        return
    }

    `$script:IRVersion = '$version'
    # Keep an existing tenant context / open case if the file is pasted again (e.g. after an update).
    if (-not (Get-Variable -Name IRContext -Scope Script -ErrorAction SilentlyContinue)) {
        `$script:IRContext = `$null
    }

"@

$body = foreach ($file in @($private + $public)) {
    $relative = [System.IO.Path]::GetRelativePath($repo, $file.FullName).Replace('\', '/')
    # Lines are copied verbatim (not indented) so here-strings in the source stay valid.
    "# ---- $relative ----"
    Get-Content -LiteralPath $file.FullName
    ''
}

$publicNames = ($public.BaseName | ForEach-Object { $_ }) -join ', '
$footer = @"
    Write-Host "EverythingIsFine v$version loaded." -ForegroundColor Green
    Write-Host 'Commands: $publicNames' -ForegroundColor Gray
    Write-Host 'Next: Connect-IR -Tenant <client-domain>' -ForegroundColor Gray
}
"@

$content = ($header.TrimEnd("`r", "`n") -split "`r?`n") + $body + ($footer -split "`r?`n")
$text = ($content -join "`n").TrimEnd() + "`n"

$outDir = Split-Path $OutputPath -Parent
if (-not (Test-Path -LiteralPath $outDir)) { New-Item -ItemType Directory -Path $outDir -Force | Out-Null }
[System.IO.File]::WriteAllText($OutputPath, $text, [System.Text.UTF8Encoding]::new($false))

$lines = ($text -split "`n").Count
Write-Host "Built $OutputPath (v$version, $lines lines, $($public.Count) public / $($private.Count) private files)"
